#!/usr/bin/env python3
"""Generates the ctypes mirror of the px4rl C parameter structs from their headers.

    gen_ctypes.py --output _structs.py include/px4rl/c_api.h include/px4rl/plant.h

The structs hold only float, int32_t and uint8_t scalars, fixed-size arrays of them (the sizes may be
PX4RL_* macros) and arrays of structs defined earlier, so a small parser is enough. Anything else is an error:
the generator never guesses a layout. Integer `#define PX4RL_*` constants are emitted as well.
"""
import argparse
import re
import sys
from pathlib import Path

SCALAR_CTYPES = {
    "float": "c_float",
    "int32_t": "c_int32",
    "uint8_t": "c_uint8",
}

STRUCT_RE = re.compile(r"typedef\s+struct\s+(\w+)\s*\{(.*?)\}\s*(\w+)\s*;", re.S)
DEFINE_RE = re.compile(r"^[ \t]*#[ \t]*define[ \t]+(PX4RL_\w+)[ \t]+(-?\d+)[ \t]*(?:/\*.*)?$", re.M)
MEMBER_RE = re.compile(r"^(\w+)\s+(\w+)((?:\s*\[[^\]]+\])*)$")
DIMENSION_RE = re.compile(r"\[\s*([^\]]+?)\s*\]")


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    return re.sub(r"//[^\n]*", " ", text)


def python_class_name(c_name):
    if not c_name.startswith("px4rl_"):
        raise ValueError(f"struct name {c_name!r} does not start with px4rl_")
    return "".join(part.capitalize() for part in c_name[len("px4rl_"):].split("_"))


def python_constant_name(c_name):
    return c_name[len("PX4RL_"):]


def resolve_dimension(token, constants):
    if token.isdigit():
        return int(token)
    if token in constants:
        return constants[token]
    raise ValueError(f"array dimension {token!r} is neither a number nor a PX4RL_* integer constant")


def parse_headers(paths):
    """Returns (constants, structs). constants maps a macro name to an int. structs is a list, in declaration
    order, of (c_name, [(field, c_type, dimensions)])."""
    constants = {}
    structs = []

    for path in paths:
        raw = Path(path).read_text()
        text = strip_comments(raw)
        constants.update({name: int(value) for name, value in DEFINE_RE.findall(raw.replace("\r", ""))})

        for tag, body, typedef_name in STRUCT_RE.findall(text):
            if tag != typedef_name:
                raise ValueError(f"{path}: typedef struct {tag} {{...}} {typedef_name}: tag and name differ")

            known = {name for name, _ in structs}
            fields = []

            for declaration in (d.strip() for d in body.split(";")):
                if not declaration:
                    continue
                match = MEMBER_RE.match(" ".join(declaration.split()))
                if match is None:
                    raise ValueError(f"{path}: cannot parse member {declaration!r} of {tag}")
                c_type, field, dimension_text = match.groups()
                if c_type not in SCALAR_CTYPES and c_type not in known:
                    raise ValueError(f"{path}: member {field} of {tag} has unsupported type {c_type!r}")
                dimensions = [resolve_dimension(t, constants) for t in DIMENSION_RE.findall(dimension_text)]
                fields.append((field, c_type, dimensions))

            if not fields:
                raise ValueError(f"{path}: struct {tag} has no members")
            structs.append((tag, fields))

    if not structs:
        raise ValueError("no struct definitions found")
    return constants, structs


def ctypes_expression(c_type, dimensions):
    expression = f"_ct.{SCALAR_CTYPES[c_type]}" if c_type in SCALAR_CTYPES else python_class_name(c_type)
    for dimension in reversed(dimensions):
        expression = f"{expression} * {dimension}"
    return expression


def render(constants, structs, header_names):
    lines = [
        '"""ctypes mirror of the px4rl C parameter structs.',
        "",
        f"Generated by tools/gen_ctypes.py from {', '.join(header_names)}. Do not edit.",
        '"""',
        "import ctypes as _ct",
        "",
    ]
    for name, value in constants.items():
        lines.append(f"{python_constant_name(name)} = {value}")

    for c_name, fields in structs:
        lines += ["", "", f"class {python_class_name(c_name)}(_ct.Structure):", f'    """C struct {c_name}."""', "", "    _fields_ = ["]
        for field, c_type, dimensions in fields:
            lines.append(f'        ("{field}", {ctypes_expression(c_type, dimensions)}),')
        lines.append("    ]")

    names = ", ".join(f'"{python_class_name(c_name)}"' for c_name, _ in structs)
    constant_names = ", ".join(f'"{python_constant_name(n)}"' for n in constants)
    lines += ["", "", f"STRUCTS = ({names},)", f"CONSTANTS = ({constant_names},)", ""]
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--output", required=True, help="Python file to write")
    parser.add_argument("headers", nargs="+", help="C headers, in dependency order")
    args = parser.parse_args(argv)

    constants, structs = parse_headers(args.headers)
    # Only the constants the Python side uses: array sizes and the position_step outcome codes.
    constants = {k: v for k, v in constants.items() if k == "PX4RL_MAX_ROTORS" or k.startswith("PX4RL_OUTCOME_")}
    Path(args.output).write_text(render(constants, structs, [Path(h).name for h in args.headers]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
